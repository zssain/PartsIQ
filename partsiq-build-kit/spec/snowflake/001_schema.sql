-- Operator executes in a dedicated development account first. No ACCOUNTADMIN in application secrets.
CREATE DATABASE IF NOT EXISTS PARTSIQ_DEV;
CREATE SCHEMA IF NOT EXISTS PARTSIQ_DEV.CATALOGUE;
CREATE SCHEMA IF NOT EXISTS PARTSIQ_DEV.REPORTING;
CREATE TABLE IF NOT EXISTS PARTSIQ_DEV.CATALOGUE.VERSIONS (
 VERSION_ID VARCHAR(36) NOT NULL, CONTENT_SHA256 VARCHAR(64) NOT NULL,
 RECORD_COUNT NUMBER(10,0) NOT NULL, CREATED_AT TIMESTAMP_TZ NOT NULL,
 PRIMARY KEY(VERSION_ID)
);
CREATE TABLE IF NOT EXISTS PARTSIQ_DEV.CATALOGUE.RECORDS (
 VERSION_ID VARCHAR(36) NOT NULL, ENTITY_TYPE VARCHAR(40) NOT NULL,
 ENTITY_KEY VARCHAR(120) NOT NULL, PAYLOAD VARIANT NOT NULL,
 ROW_SHA256 VARCHAR(64) NOT NULL, PRIMARY KEY(VERSION_ID,ENTITY_TYPE,ENTITY_KEY)
);
CREATE TABLE IF NOT EXISTS PARTSIQ_DEV.CATALOGUE.STOCK_SNAPSHOTS (
 SNAPSHOT_ID VARCHAR(36) NOT NULL, PART_ID NUMBER(10,0) NOT NULL,
 WAREHOUSE_ID NUMBER(5,0) NOT NULL, ON_HAND NUMBER(10,3) NOT NULL,
 RESERVED NUMBER(10,3) NOT NULL, OBSERVED_AT TIMESTAMP_TZ NOT NULL,
 PRIMARY KEY(SNAPSHOT_ID,PART_ID,WAREHOUSE_ID)
);
CREATE TABLE IF NOT EXISTS PARTSIQ_DEV.REPORTING.EVENTS (
 EVENT_ID VARCHAR(36) NOT NULL, EVENT_TYPE VARCHAR(60) NOT NULL,
 OCCURRED_AT TIMESTAMP_TZ NOT NULL, IS_DEMO BOOLEAN NOT NULL,
 STATUS VARCHAR(40), STAGE VARCHAR(40), DURATION_MS NUMBER(12,3),
 INPUT_TOKENS NUMBER(12,0), OUTPUT_TOKENS NUMBER(12,0), ESTIMATED_COST_USD NUMBER(18,8),
 PRIMARY KEY(EVENT_ID)
);
CREATE VIEW IF NOT EXISTS PARTSIQ_DEV.REPORTING.DAILY_METRICS AS
 SELECT DATE_TRUNC('DAY',OCCURRED_AT) AS DAY, IS_DEMO, EVENT_TYPE,
 COUNT(*) AS EVENT_COUNT, AVG(DURATION_MS) AS MEAN_DURATION_MS,
 SUM(ESTIMATED_COST_USD) AS ESTIMATED_COST_USD
 FROM PARTSIQ_DEV.REPORTING.EVENTS GROUP BY 1,2,3;
-- PK declarations are metadata. Publication and outbox writers validate uniqueness themselves.
