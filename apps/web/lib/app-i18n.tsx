/** Both dictionaries, exported for the completeness test. */
export const APP_DICTIONARIES: Readonly<Record<AppLocale, Readonly<Record<Key, string>>>> = { en: EN, ar: AR };

type Vars = Record<string, string | number>;

function lookup(locale: AppLocale, key: Key): string {
  return (locale === "ar" ? AR[key] : EN[key]) ?? EN[key] ?? key;
}

function fill(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function isKey(key: string): key is Key {
  return Object.prototype.hasOwnProperty.call(EN, key);
}

/** Pure translator, for code outside React (and tests). */
export function translate(locale: AppLocale, key: Key, vars?: Vars): string {
  return fill(lookup(locale, key), vars);
}

const LocaleContext = createContext<AppLocale>("en");

export function AppLocaleProvider({ locale, children }: { locale: AppLocale; children: ReactNode }): JSX.Element {
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

export function useLocale(): AppLocale {
  return useContext(LocaleContext);
}

export function useT(): (key: Key, vars?: Vars) => string {
  const locale = useContext(LocaleContext);
  return useCallback((key: Key, vars?: Vars) => translate(locale, key, vars), [locale]);
}

/**
 * Rich interpolation: placeholders may be React nodes (typically a <bdi> identifier), so the
 * surrounding sentence follows the active language's word order without string concatenation.
 */
export function useTx(): (key: Key, vars: Record<string, ReactNode>) => JSX.Element {
  const locale = useContext(LocaleContext);
  return useCallback((key: Key, vars: Record<string, ReactNode>) => {
    const parts = lookup(locale, key).split(/\{(\w+)\}/);
    return (
      <>
        {parts.map((part, i) => (i % 2 === 1
          ? <Fragment key={i}>{part in vars ? vars[part] : `{${part}}`}</Fragment>
          : part ? <Fragment key={i}>{part}</Fragment> : null))}
      </>
    );
  }, [locale]);
}

/**
 * Label for a server enum/code (`${prefix}.${code}`). English keeps the server's own label when
 * one is supplied (it is the authoritative wording); otherwise the dictionary is used, and an
 * unknown code falls back to the server label or the raw code so nothing renders blank.
 */
export function useLabel(): (prefix: string, code: string | null | undefined, serverLabel?: string | null) => string {
  const locale = useContext(LocaleContext);
  return useCallback((prefix: string, code: string | null | undefined, serverLabel?: string | null) => {
    if (code === null || code === undefined || code === "") return serverLabel ?? "";
    if (locale === "en" && serverLabel) return serverLabel;
    const key = `${prefix}.${code}`;
    if (isKey(key)) return lookup(locale, key);
    return serverLabel ?? code;
  }, [locale]);
}

